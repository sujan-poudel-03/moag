// ─── tsconfig / jsconfig path aliases — read from manifests, and "unknown" when they cannot be ───

import { strict as assert } from 'assert';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { readImportPathScopes, stripJsonComments } from '../../../runner/import-paths';

const made: string[] = [];

function repo(files: Record<string, string>): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'moag-import-paths-'));
  made.push(dir);
  for (const [rel, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), content);
  }
  return dir;
}

const json = (value: unknown): string => JSON.stringify(value, null, 2);

describe('import paths — stripJsonComments', () => {
  it('removes comments and trailing commas, and leaves strings alone', () => {
    const text = [
      '{',
      '  // a line comment',
      '  "a": "http://x.dev//not-a-comment", /* inline */',
      '  "b": ["one, ]", "two",],',
      '  "c": "quote \\" // still a string",',
      '}',
    ].join('\n');
    assert.deepEqual(JSON.parse(stripJsonComments(text)), {
      a: 'http://x.dev//not-a-comment', b: ['one, ]', 'two'], c: 'quote " // still a string',
    });
  });

  it('never throws on text that is not JSON at all', () => {
    for (const text of ['', '"open', '/* open', '{ "a": ', '\\']) {
      assert.equal(typeof stripJsonComments(text), 'string');
    }
  });
});

describe('import paths — readImportPathScopes', () => {
  after(() => {
    for (const dir of made) { fs.rmSync(dir, { recursive: true, force: true }); }
  });

  it('returns nothing for a repository with no config, or with configs that declare no alias', () => {
    assert.deepEqual(readImportPathScopes(repo({ 'src/a.ts': '' }), ['src/a.ts']), []);
    const plain = repo({ 'tsconfig.json': json({ compilerOptions: { strict: true } }), 'jsconfig.json': '{}' });
    assert.deepEqual(readImportPathScopes(plain, ['src/a.ts']), []);
  });

  it('reads paths from a tsconfig written with comments and trailing commas, relative to the config', () => {
    const dir = repo({
      'tsconfig.json': '{\n  // generated by tsc --init\n  "compilerOptions": {\n    "paths": { "@infra/*": ["./src/infra/*"], "@db": ["src/infra/db.ts"], },\n  },\n}\n',
    });
    assert.deepEqual(readImportPathScopes(dir, []), [{
      dir: '',
      aliases: [{ pattern: '@infra/*', targets: ['src/infra/*'] }, { pattern: '@db', targets: ['src/infra/db.ts'] }],
    }]);
  });

  it('resolves targets from baseUrl when there is one, and carries the baseUrl itself as the catch-all', () => {
    const dir = repo({ 'tsconfig.json': json({ compilerOptions: { baseUrl: 'src', paths: { '@app/*': ['*'], '$lib/*': ['lib/*'] } } }) });
    assert.deepEqual(readImportPathScopes(dir, []), [{
      dir: '',
      aliases: [
        { pattern: '@app/*', targets: ['src/*'] }, { pattern: '$lib/*', targets: ['src/lib/*'] }, { pattern: '*', targets: ['src/*'] },
      ],
    }]);
    const rootBase = repo({ 'jsconfig.json': json({ compilerOptions: { baseUrl: '.' } }) });
    assert.deepEqual(readImportPathScopes(rootBase, []), [{ dir: '', aliases: [{ pattern: '*', targets: ['*'] }] }]);
  });

  it('follows extends inside the repository: Nx keeps paths in tsconfig.base.json, and a child overrides wholesale', () => {
    const nx = repo({
      'tsconfig.base.json': json({ compilerOptions: { paths: { '@acme/db': ['libs/db/src/index.ts'] } } }),
      'apps/api/tsconfig.json': json({ extends: '../../tsconfig.base.json', compilerOptions: { outDir: 'dist' } }),
      'apps/web/tsconfig.json': json({ extends: '../../tsconfig.base', compilerOptions: { paths: { '~/*': ['./src/*'] } } }),
    });
    const scopes = readImportPathScopes(nx, ['apps/api/src/main.ts', 'apps/web/src/page.tsx', 'README.md']);
    assert.deepEqual(scopes, [
      { dir: '', aliases: [{ pattern: '@acme/db', targets: ['libs/db/src/index.ts'] }] },
      { dir: 'apps/api', aliases: [{ pattern: '@acme/db', targets: ['libs/db/src/index.ts'] }] },
      { dir: 'apps/web', aliases: [{ pattern: '~/*', targets: ['apps/web/src/*'] }] },
    ]);
  });

  it('follows extends into an installed package, and an array of bases in order', () => {
    const dir = repo({
      'node_modules/@tsconfig/node20/tsconfig.json': json({ compilerOptions: { strict: true } }),
      'tsconfig.paths.json': json({ compilerOptions: { paths: { '@infra/*': ['src/infra/*'] } } }),
      'tsconfig.json': json({ extends: ['@tsconfig/node20/tsconfig.json', './tsconfig.paths.json'] }),
    });
    assert.deepEqual(readImportPathScopes(dir, []), [{ dir: '', aliases: [{ pattern: '@infra/*', targets: ['src/infra/*'] }] }]);
  });

  it('drops a target outside the repository: it is in none of its layers', () => {
    const dir = repo({ 'tsconfig.json': json({ compilerOptions: { paths: { '@shared/*': ['../shared/*', 'src/shared/*'] } } }) });
    assert.deepEqual(readImportPathScopes(dir, []), [{ dir: '', aliases: [{ pattern: '@shared/*', targets: ['src/shared/*'] }] }]);
  });

  // The failure paths: each of these may hide an alias, so each is "unknown", never "none".
  it('reports a scope as unknown when its config cannot be read or its base cannot be followed', () => {
    const cases: Array<[string, Record<string, string>]> = [
      ['invalid JSON', { 'tsconfig.json': '{ "compilerOptions": { "paths": ' }],
      ['not an object', { 'tsconfig.json': '[]' }],
      ['oversize', { 'tsconfig.json': `{ "pad": "${'x'.repeat(300 * 1024)}" }` }],
      ['extends a missing file', { 'tsconfig.json': json({ extends: './tsconfig.base.json' }) }],
      ['extends a package that is not installed', { 'tsconfig.json': json({ extends: '@tsconfig/node20/tsconfig.json' }) }],
      ['extends a file outside the repository', { 'tsconfig.json': json({ extends: '../outside.json' }) }],
      ['extends itself', { 'tsconfig.json': json({ extends: './tsconfig.json' }) }],
      ['an unreadable base', { 'tsconfig.json': json({ extends: './base.json' }), 'base.json': 'not json' }],
      ['paths that is not a map', { 'tsconfig.json': json({ compilerOptions: { paths: ['src/*'] } }) }],
      ['a target that is not a string', { 'tsconfig.json': json({ compilerOptions: { paths: { '@a/*': [1] } } }) }],
      ['a pattern with two stars', { 'tsconfig.json': json({ compilerOptions: { paths: { '@a/*/*': ['src/*'] } } }) }],
      ['a template variable', { 'tsconfig.json': json({ compilerOptions: { paths: { '@a/*': ['${configDir}/src/*'] } } }) }],
      ['an absolute target', { 'tsconfig.json': json({ compilerOptions: { paths: { '@a/*': ['/abs/src/*'] } } }) }],
      ['a baseUrl outside the repository', { 'tsconfig.json': json({ compilerOptions: { baseUrl: '..' } }) }],
      ['compilerOptions that is not an object', { 'jsconfig.json': json({ compilerOptions: 'x' }) }],
      ['one readable config beside an unreadable one', {
        'tsconfig.json': json({ compilerOptions: { paths: { '@a/*': ['src/*'] } } }), 'tsconfig.base.json': '{',
      }],
    ];
    for (const [label, files] of cases) {
      assert.deepEqual(readImportPathScopes(repo(files), ['src/a.ts']), [{ dir: '', aliases: null }], label);
    }
  });

  it('a config that is a directory is unknown, and one above a changed file is its own scope', () => {
    const dir = repo({ 'packages/api/tsconfig.json': '{ broken', 'packages/api/src/a.ts': '', 'packages/web/src/b.ts': '' });
    fs.mkdirSync(path.join(dir, 'jsconfig.json'));
    assert.deepEqual(readImportPathScopes(dir, ['packages/api/src/a.ts', 'packages/web/src/b.ts']), [
      { dir: '', aliases: null },
      { dir: 'packages/api', aliases: null },
    ]);
  });

  it('only looks above changed JS and TS files, and never inside node_modules', () => {
    const dir = repo({
      'docs/tsconfig.json': '{ broken',
      'node_modules/dep/tsconfig.json': '{ broken',
    });
    assert.deepEqual(readImportPathScopes(dir, ['docs/readme.md', 'node_modules/dep/index.js']), []);
    assert.deepEqual(readImportPathScopes(dir, ['docs/example.ts']), [{ dir: 'docs', aliases: null }]);
  });

  // A "solution" tsconfig holds no paths of its own: Vite, Angular and Nx keep them in the
  // configs it refers to. Unread, every `@/x` below it was either unplaced or — worse, for a
  // scoped-looking alias — taken for a published package.
  it('follows project references one level: a solution config whose paths live in tsconfig.app.json', () => {
    const vite = repo({
      'tsconfig.json': json({ files: [], references: [{ path: './tsconfig.app.json' }, { path: './tsconfig.node.json' }] }),
      'tsconfig.app.json': '{\n  /* app */\n  "compilerOptions": { "baseUrl": ".", "paths": { "@/*": ["./src/*"], "@infra/*": ["src/infra/*"] } },\n  "include": ["src"],\n}\n',
      'tsconfig.node.json': json({ compilerOptions: { composite: true }, include: ['vite.config.ts'] }),
    });
    assert.deepEqual(readImportPathScopes(vite, ['src/domain/order.ts']), [{
      dir: '',
      aliases: [{ pattern: '@/*', targets: ['src/*'] }, { pattern: '@infra/*', targets: ['src/infra/*'] }, { pattern: '*', targets: ['*'] }],
    }]);
  });

  it('a reference to a directory reads its tsconfig.json, applies below that directory, and follows what it extends', () => {
    const mono = repo({
      'tsconfig.json': json({ files: [], references: [{ path: './packages/api' }, { path: 'packages/web/tsconfig.build.json' }] }),
      'tsconfig.base.json': json({ compilerOptions: { paths: { '@acme/db': ['libs/db/src/index.ts'] } } }),
      'packages/api/tsconfig.json': json({ extends: '../../tsconfig.base.json' }),
      'packages/web/tsconfig.build.json': json({ compilerOptions: { paths: { '~/*': ['./src/*'] } } }),
    });
    // No changed file sits under either package: the scopes come from the references alone.
    assert.deepEqual(readImportPathScopes(mono, ['README.md']), [
      { dir: '', aliases: [{ pattern: '@acme/db', targets: ['libs/db/src/index.ts'] }] },
      { dir: 'packages/api', aliases: [{ pattern: '@acme/db', targets: ['libs/db/src/index.ts'] }] },
      { dir: 'packages/web', aliases: [{ pattern: '~/*', targets: ['packages/web/src/*'] }] },
    ]);
  });

  it('only one level: the references of a referenced config are not followed', () => {
    const dir = repo({
      'tsconfig.json': json({ references: [{ path: './a' }] }),
      'a/tsconfig.json': json({ compilerOptions: { paths: { '@a/*': ['./src/*'] } }, references: [{ path: '../b' }] }),
      'b/tsconfig.json': json({ compilerOptions: { paths: { '@b/*': ['./src/*'] } } }),
    });
    assert.deepEqual(readImportPathScopes(dir, []), [{ dir: 'a', aliases: [{ pattern: '@a/*', targets: ['a/src/*'] }] }]);
    // A changed file under b/ brings b's own config in the ordinary way.
    assert.deepEqual(readImportPathScopes(dir, ['b/src/x.ts']).map((s) => s.dir), ['a', 'b']);
  });

  it('a config that is both probed and referenced contributes each alias once', () => {
    const dir = repo({
      'tsconfig.json': json({ references: [{ path: './tsconfig.base.json' }] }),
      'tsconfig.base.json': json({ compilerOptions: { paths: { '@a/*': ['src/*'] } } }),
    });
    assert.deepEqual(readImportPathScopes(dir, []), [{ dir: '', aliases: [{ pattern: '@a/*', targets: ['src/*'] }] }]);
  });

  // The failure paths of a reference: the referenced config may be the one that maps the
  // imports, so what cannot be read is "unknown" where it applies — never "no aliases".
  it('a referenced config that is missing, unreadable or malformed leaves its scope unknown', () => {
    const cases: Array<[string, Record<string, string>, Array<{ dir: string; aliases: null }>]> = [
      ['a missing file', { 'tsconfig.json': json({ references: [{ path: './tsconfig.app.json' }] }) }, [{ dir: '', aliases: null }]],
      ['a missing directory project', { 'tsconfig.json': json({ references: [{ path: './packages/api' }] }) }, [{ dir: 'packages/api', aliases: null }]],
      ['invalid JSON', { 'tsconfig.json': json({ references: [{ path: './apps/web' }] }), 'apps/web/tsconfig.json': '{ "compilerOptions": ' },
        [{ dir: 'apps/web', aliases: null }]],
      ['a referenced config whose base is missing',
        { 'tsconfig.json': json({ references: [{ path: './tsconfig.app.json' }] }), 'tsconfig.app.json': json({ extends: './nope.json' }) },
        [{ dir: '', aliases: null }]],
      ['references that is not a list', { 'tsconfig.json': json({ references: { path: './a' } }) }, [{ dir: '', aliases: null }]],
      ['a reference with no path', { 'tsconfig.json': json({ references: [{ prepend: true }] }) }, [{ dir: '', aliases: null }]],
      ['a reference whose path is not a string', { 'tsconfig.json': json({ references: [{ path: 7 }] }) }, [{ dir: '', aliases: null }]],
      ['more references than are read', { 'tsconfig.json': json({ references: Array.from({ length: 51 }, (_, i) => ({ path: `./p${i}` })) }) },
        [{ dir: '', aliases: null }]],
    ];
    for (const [label, files, expected] of cases) {
      assert.deepEqual(readImportPathScopes(repo(files), ['src/a.ts']), expected, label);
    }
  });

  it('a reference that leaves the repository applies to nothing here, and a config that refers to itself is read once', () => {
    const outside = repo({ 'tsconfig.json': json({ references: [{ path: '../elsewhere' }], compilerOptions: { paths: { '@a/*': ['src/*'] } } }) });
    assert.deepEqual(readImportPathScopes(outside, []), [{ dir: '', aliases: [{ pattern: '@a/*', targets: ['src/*'] }] }]);
    const self = repo({ 'tsconfig.json': json({ references: [{ path: './tsconfig.json' }, { path: '.' }], compilerOptions: { paths: { '@a/*': ['src/*'] } } }) });
    assert.deepEqual(readImportPathScopes(self, []), [{ dir: '', aliases: [{ pattern: '@a/*', targets: ['src/*'] }] }]);
  });

  it('does not follow a symlinked config', function () {
    const dir = repo({ 'elsewhere.json': json({ compilerOptions: { paths: { '@a/*': ['src/*'] } } }) });
    try {
      fs.symlinkSync(path.join(dir, 'elsewhere.json'), path.join(dir, 'tsconfig.json'));
    } catch {
      this.skip();
      return;
    }
    assert.deepEqual(readImportPathScopes(dir, []), [{ dir: '', aliases: null }]);
  });
});
